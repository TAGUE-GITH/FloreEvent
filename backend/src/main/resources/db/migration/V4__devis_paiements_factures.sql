-- Devis : remise accordee, message au client, date limite d'acceptation
ALTER TABLE booking ADD COLUMN discount_cents INTEGER NOT NULL DEFAULT 0 CHECK (discount_cents >= 0);
ALTER TABLE booking ADD COLUMN quote_message VARCHAR(1000);
ALTER TABLE booking ADD COLUMN quote_valid_until DATE;
-- Annulation d'une reservation confirmee : somme gardee selon la regle du cahier des charges
ALTER TABLE booking ADD COLUMN cancellation_fee_cents INTEGER CHECK (cancellation_fee_cents >= 0);

-- Paiements recus : carte (page Stripe, R8) ou hors ligne (virement, cheque, especes)
CREATE TABLE payment (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id            BIGINT      NOT NULL REFERENCES booking (id),
    method                VARCHAR(20) NOT NULL CHECK (method IN ('CARTE', 'VIREMENT', 'CHEQUE', 'ESPECES')),
    status                VARCHAR(20) NOT NULL CHECK (status IN ('EN_ATTENTE', 'PAYE', 'REMBOURSE')),
    amount_cents          INTEGER     NOT NULL CHECK (amount_cents > 0),
    refunded_cents        INTEGER     NOT NULL DEFAULT 0 CHECK (refunded_cents >= 0),
    -- Session Stripe Checkout : un meme paiement n'est jamais compte deux fois
    checkout_session_id   VARCHAR(255) UNIQUE,
    payment_intent_id     VARCHAR(255),
    note                  VARCHAR(255),
    author_id             BIGINT REFERENCES app_user (id),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at               TIMESTAMP WITH TIME ZONE,
    CHECK (refunded_cents <= amount_cents)
);

CREATE INDEX idx_payment_booking ON payment (booking_id);

-- Factures et avoirs : numerotation continue par annee, sans trou (R6)
CREATE TABLE invoice_counter (
    invoice_year INTEGER PRIMARY KEY,
    last_number INTEGER NOT NULL
);

CREATE TABLE invoice (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       VARCHAR(20) NOT NULL UNIQUE,
    booking_id   BIGINT      NOT NULL REFERENCES booking (id),
    payment_id   BIGINT REFERENCES payment (id),
    kind         VARCHAR(20) NOT NULL CHECK (kind IN ('ACOMPTE', 'SOLDE', 'AVOIR')),
    -- TTC en centimes ; un avoir (remboursement) est negatif
    amount_cents INTEGER     NOT NULL,
    issued_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_invoice_booking ON invoice (booking_id);
