-- Sprints 5 et 6 : prestations (decoration florale...), mot de passe oublie, messages du formulaire de contact

-- US-18 : prestations proposees avec le materiel (prix TTC « a partir de », ajuste si besoin par la remise du devis)
CREATE TABLE prestation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(1000),
    price_cents INTEGER      NOT NULL CHECK (price_cents >= 0),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Prestations d'une reservation : nom et prix figes a la demande (R3)
CREATE TABLE booking_prestation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT       NOT NULL REFERENCES booking (id),
    prestation_id BIGINT       NOT NULL REFERENCES prestation (id),
    name          VARCHAR(120) NOT NULL,
    price_cents   INTEGER      NOT NULL CHECK (price_cents >= 0)
);

CREATE INDEX idx_booking_prestation_booking ON booking_prestation (booking_id);

ALTER TABLE booking ADD COLUMN prestations_cents INTEGER NOT NULL DEFAULT 0 CHECK (prestations_cents >= 0);

-- US-22 : lien « mot de passe oublie » a usage unique ; seule son empreinte est stockee
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- US-21 : messages envoyes depuis la page contact du site
CREATE TABLE contact_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120)  NOT NULL,
    email      VARCHAR(160)  NOT NULL,
    phone      VARCHAR(30),
    event_date DATE,
    message    VARCHAR(2000) NOT NULL,
    handled    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
