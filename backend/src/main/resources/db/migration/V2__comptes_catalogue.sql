-- Sprint 1 : comptes de l'equipe, photos, catalogue de location et materiel en reparation

-- Images (photos de profil et des articles) stockees en base : le disque des hebergeurs gratuits est efface
-- a chaque redeploiement. Identifiant aleatoire : l'adresse ne peut pas etre devinee.
CREATE TABLE image (
    id           VARCHAR(36)     PRIMARY KEY,
    content_type VARCHAR(30)     NOT NULL,
    data         VARCHAR(400000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(80)  NOT NULL,
    last_name     VARCHAR(80)  NOT NULL,
    phone         VARCHAR(30),
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('GERANT', 'COMMERCIAL', 'LOGISTIQUE', 'CLIENT')),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    avatar_id     VARCHAR(36) REFERENCES image (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

-- Montants en centimes d'euro (R5)
CREATE TABLE item (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference               VARCHAR(40)   NOT NULL UNIQUE,
    name                    VARCHAR(160)  NOT NULL,
    category_id             BIGINT        NOT NULL REFERENCES category (id),
    description             VARCHAR(2000),
    day_price_cents         INTEGER       NOT NULL CHECK (day_price_cents > 0),
    -- Prix facture en cas de casse ou de perte (R7)
    replacement_value_cents INTEGER       NOT NULL CHECK (replacement_value_cents >= 0),
    setup_price_cents       INTEGER       NOT NULL DEFAULT 0 CHECK (setup_price_cents >= 0),
    quantity                INTEGER       NOT NULL CHECK (quantity >= 0),
    active                  BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_item_category ON item (category_id);

-- Photos d'un article, dans l'ordre d'affichage (la premiere est la photo principale)
CREATE TABLE item_image (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id  BIGINT      NOT NULL REFERENCES item (id),
    image_id VARCHAR(36) NOT NULL REFERENCES image (id),
    position INTEGER     NOT NULL
);

CREATE INDEX idx_item_image_item ON item_image (item_id);

-- Exemplaires retires de la location pour une periode (R1) ; to_date vide : jusqu'a nouvel ordre
CREATE TABLE maintenance (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT       NOT NULL REFERENCES item (id),
    quantity   INTEGER      NOT NULL CHECK (quantity > 0),
    from_date  DATE         NOT NULL,
    to_date    DATE,
    reason     VARCHAR(255),
    author_id  BIGINT       NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (to_date IS NULL OR to_date >= from_date)
);

CREATE INDEX idx_maintenance_item ON maintenance (item_id, from_date);
