-- Sprint 2 : comptes clients, demandes de devis et reservations

CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(120) NOT NULL,
    company    VARCHAR(120),
    phone      VARCHAR(30)  NOT NULL,
    email      VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Un compte client est relie a sa fiche client ; conditions acceptees : version et date (preuve)
ALTER TABLE app_user ADD COLUMN customer_id BIGINT UNIQUE REFERENCES customer (id);
ALTER TABLE app_user ADD COLUMN terms_accepted_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE app_user ADD COLUMN terms_version VARCHAR(20);

-- Montants TTC en centimes d'euro (R5), figes au moment de la demande (R3)
CREATE TABLE booking (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RES-2026-00001, attribuee juste apres l'enregistrement
    reference              VARCHAR(20) UNIQUE,
    customer_id            BIGINT      NOT NULL REFERENCES customer (id),
    status                 VARCHAR(20) NOT NULL
        CHECK (status IN ('DEMANDE', 'DEVIS', 'CONFIRMEE', 'EN_COURS', 'RETOURNEE', 'CLOTUREE', 'ANNULEE')),
    start_date             DATE        NOT NULL,
    end_date               DATE        NOT NULL,
    delivery_mode          VARCHAR(20) NOT NULL CHECK (delivery_mode IN ('RETRAIT', 'LIVRAISON')),
    address                VARCHAR(255),
    distance_km            INTEGER,
    installation           BOOLEAN     NOT NULL DEFAULT FALSE,
    note                   VARCHAR(1000),
    rental_cents           INTEGER     NOT NULL CHECK (rental_cents >= 0),
    setup_cents            INTEGER     NOT NULL CHECK (setup_cents >= 0),
    delivery_cents         INTEGER     NOT NULL CHECK (delivery_cents >= 0),
    total_cents            INTEGER     NOT NULL CHECK (total_cents >= 0),
    deposit_cents          INTEGER     NOT NULL CHECK (deposit_cents >= 0),
    security_deposit_cents INTEGER     NOT NULL CHECK (security_deposit_cents >= 0),
    terms_version          VARCHAR(20),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

-- Recherche des reservations qui chevauchent une periode (disponibilites, R1)
CREATE INDEX idx_booking_period ON booking (status, start_date, end_date);
CREATE INDEX idx_booking_customer ON booking (customer_id);

CREATE TABLE booking_line (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id              BIGINT       NOT NULL REFERENCES booking (id),
    item_id                 BIGINT       NOT NULL REFERENCES item (id),
    item_name               VARCHAR(160) NOT NULL,
    quantity                INTEGER      NOT NULL CHECK (quantity > 0),
    day_price_cents         INTEGER      NOT NULL,
    setup_price_cents       INTEGER      NOT NULL,
    replacement_value_cents INTEGER      NOT NULL,
    line_total_cents        INTEGER      NOT NULL
);

CREATE INDEX idx_booking_line_booking ON booking_line (booking_id);
CREATE INDEX idx_booking_line_item ON booking_line (item_id);

-- Historique des etapes (R4) : qui, quand
CREATE TABLE booking_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT      NOT NULL REFERENCES booking (id),
    status     VARCHAR(20) NOT NULL,
    note       VARCHAR(500),
    author_id  BIGINT REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
